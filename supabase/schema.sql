-- WebCollector: Supabase schema.
-- Paste into Supabase Dashboard -> SQL Editor -> New query -> Run.
-- Safe to re-run (idempotent).

create table if not exists wc_boards (
  id          text primary key,                    -- UUID generated by the extension
  name        text not null,
  color       text,
  description text,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now(),
  deleted_at  timestamptz                          -- tombstone for deletions
);

create table if not exists wc_items (
  id          text primary key,
  type        text not null default 'page',        -- shorts | video | reel | social | article | page
  title       text not null default '',
  url         text not null default '',
  canonical   text,
  thumbnail   text,
  description text,
  source      text,
  selection   text,
  note        text,
  board_id    text not null default 'inbox',
  tags        jsonb not null default '[]'::jsonb,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now(),
  deleted_at  timestamptz
);

create index if not exists wc_items_updated_at_idx on wc_items (updated_at);
create index if not exists wc_items_board_idx     on wc_items (board_id);
create index if not exists wc_boards_updated_at_idx on wc_boards (updated_at);

-- Personal-use row level security: allow anyone holding your project's
-- anon key to read/write (single user, private project). If you later add
-- Supabase Auth, replace these with user-scoped policies.
alter table wc_boards enable row level security;
alter table wc_items  enable row level security;

drop policy if exists "wc_boards_any" on wc_boards;
create policy "wc_boards_any" on wc_boards
  for all using (true) with check (true);

drop policy if exists "wc_items_any" on wc_items;
create policy "wc_items_any" on wc_items
  for all using (true) with check (true);
